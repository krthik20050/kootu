"""Export the OpenAPI contract and frontend models; --check detects drift in CI."""

import argparse
import json
from pathlib import Path

from app.core.config import Settings
from app.main import create_app


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        fields = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
            for name, value in schema.get("properties", {}).items()
        ]
        if not fields:
            extra = schema.get("additionalProperties")
            return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
        return "{\n  " + "\n  ".join(fields) + "\n}"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    schema = create_app(Settings(app_env="test", _env_file=None)).openapi()
    declarations = "// Generated by apps/api/export_contracts.py. Do not edit by hand.\n\n"
    declarations += (
        "\n\n".join(
            f"export type {name} = {ts_type(value)};"
            for name, value in sorted(schema["components"]["schemas"].items())
        )
        + "\n"
    )
    outputs = {
        root / "docs/openapi.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        root / "apps/web/src/lib/api/generated.ts": declarations,
    }
    for path, content in outputs.items():
        if arguments.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Contract drift: regenerate {path.name}")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
