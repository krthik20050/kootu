"""Distribute the central local configuration without exposing secret values."""

import json
import re
import tempfile
from pathlib import Path

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "backend/.env": "backend/.env.example",
    "frontend/.env.local": "frontend/.env.example",
    "database/.env.supabase": None,
}
DATABASE_KEYS = (
    "SUPABASE_DB_PASSWORD",
    "SUPABASE_API_DB_PASSWORD",
    "SUPABASE_MIGRATION_DATABASE_URL",
)


def sync_environment(root: Path = ROOT) -> None:
    source = root / ".environment/.env"
    if not source.is_file():
        raise ValueError("Create .environment/.env using the example before syncing")
    text = source.read_text(encoding="utf-8")
    names = re.findall(r"^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=", text, re.MULTILINE)
    if len(names) != len(set(names)):
        raise ValueError(
            "Central .env contains duplicate variable names; resolve them first"
        )
    values = dotenv_values(source, interpolate=False)
    pending = []
    for target, example in TARGETS.items():
        keys = (
            tuple(dotenv_values(root / example, interpolate=False))
            if example
            else DATABASE_KEYS
        )
        missing = [key for key in keys if key not in values]
        if missing:
            raise ValueError(
                f"Central .env is missing variable names for {target}: {', '.join(missing)}"
            )
        destination = root / target
        existing = (
            dotenv_values(destination, interpolate=False)
            if destination.exists()
            else {}
        )
        cleared = [key for key in keys if existing.get(key) and not values.get(key)]
        if cleared:
            raise ValueError(
                f"Refusing to clear saved values in {target}: {', '.join(cleared)}"
            )
        # Only this target's allowlisted settings are written. Provider/database keys
        # never enter Next.js public configuration, even though the source is shared.
        rendered = (
            "# Generated by scripts/sync_env.py; edit .environment/.env instead.\n"
        )
        rendered += (
            "\n".join(f"{key}={json.dumps(values[key] or '')}" for key in keys) + "\n"
        )
        pending.append((destination, rendered))
    # Validate every target before modifying any file.
    for destination, rendered in pending:
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=destination.parent,
            prefix=".env.sync-",
            delete=False,
        ) as temporary:
            temporary.write(rendered)
            temporary_path = Path(temporary.name)
        try:
            temporary_path.replace(destination)
        finally:
            temporary_path.unlink(missing_ok=True)
        print(f"Synced {destination.relative_to(root)} (values hidden)")


if __name__ == "__main__":
    try:
        sync_environment()
    except ValueError as error:
        raise SystemExit(str(error)) from None
